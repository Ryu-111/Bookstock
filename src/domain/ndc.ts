export interface NdcGroup {
  /** 類（0〜9） */
  classCode: number;
  className: string;
  /** 綱（00〜99）。2桁目がない分類はundefined */
  divisionCode?: string;
  divisionName?: string;
}

/** NDCの記号（913.6、007.6、K913 など）を類・綱に分ける。読めなければnull。 */
export function parseNdc(value: string | undefined): NdcGroup | null {
  const match = /^\D*(\d)(\d)?/.exec(value?.normalize('NFKC').trim() ?? '');
  if (!match?.[1]) return null;
  const classCode = Number(match[1]);
  const group: NdcGroup = {
    classCode,
    className: NDC_CLASSES[classCode] ?? String(classCode),
  };
  if (match[2] !== undefined) {
    const divisionCode = `${match[1]}${match[2]}`;
    group.divisionCode = divisionCode;
    group.divisionName = DIVISIONS[divisionCode] ?? divisionCode;
  }
  return group;
}

