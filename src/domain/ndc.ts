/** Cコード（4桁）の内容から、近いNDCの類・綱を返す。読めなければnull。 */
export function ccodeToNdc(ccode: string | undefined): NdcGroup | null {
  const content = /^\d{2}(\d{2})$/.exec(ccode ?? '')?.[1];
  if (!content) return null;
  return parseNdc(CCODE_DIVISIONS[content] ?? content.slice(0, 1));
}

/** 本の分類。NDCを優先し、なければCコードから近いものを使う。 */
export function bookClass(book: {
  ndc?: string;
  ccode?: string;
}): NdcGroup | null {
  return parseNdc(book.ndc) ?? ccodeToNdc(book.ccode);
}
